-- ─────────────────────────────────────────────────────────────────────────────
-- Collapse DUPLICATE roster rows (same email, two ids) into one canonical row.
-- Cause: the membership import created rows keyed by email ('email:<addr>') while
-- GymOS webhooks key by the member's Quoox id — so many members have two rows, and
-- a cancellation landing on one is masked by a stale 'active' row on the other.
--
-- Canonical row = the one GymOS webhooks target: prefer a row whose id equals its
-- gymos_member_id (a real Quoox id), else any row with a gymos_member_id, else the
-- most recently updated. Child records are repointed to the canonical id, a
-- cancellation / manual-inactive / ended_on on a losing row is carried forward so
-- merging never resurrects someone, then the losing rows are deleted.
--
-- SAFE TO RE-RUN. Wrapped in a transaction. Run once in the Supabase SQL editor.
-- ─────────────────────────────────────────────────────────────────────────────
begin;

create temp table _dupe_map on commit drop as
with ranked as (
  select id,
         lower(email) as em,
         gymos_member_id,
         row_number() over (
           partition by lower(email)
           order by (id = gymos_member_id) desc,         -- real Quoox-id row first
                    (gymos_member_id is not null) desc,  -- else any with a Quoox id
                    (manual_inactive_at is not null) desc,
                    updated_at desc nulls last
         ) as rn
  from public.gym_members
  where email is not null and email <> ''
),
keep as (select em, id as keep_id from ranked where rn = 1)
select r.id as loser_id, k.keep_id
from ranked r
join keep k using (em)
where r.rn > 1 and r.id <> k.keep_id;

-- Carry a cancellation / manual-inactive / ended_on from a losing row onto the keeper,
-- so the merge never loses the fact that someone had left.
update public.gym_members g set
  status = case
    when exists (select 1 from public.gym_members l join _dupe_map m on l.id = m.loser_id
                 where m.keep_id = g.id and l.status = 'cancelled')
         and g.status <> 'active'            -- don't override a genuinely active membership
    then 'cancelled' else g.status end,
  manual_inactive_at = coalesce(
    g.manual_inactive_at,
    (select max(l.manual_inactive_at) from public.gym_members l
     join _dupe_map m on l.id = m.loser_id where m.keep_id = g.id)),
  ended_on = coalesce(
    g.ended_on,
    (select max(l.ended_on) from public.gym_members l
     join _dupe_map m on l.id = m.loser_id where m.keep_id = g.id))
where g.id in (select keep_id from _dupe_map);

-- Repoint child records from losing ids to the keeper.
update public.scan_events s set member_ref = m.keep_id
  from _dupe_map m where s.member_ref = m.loser_id;

update public.membership_status_history h set member_ref = m.keep_id
  from _dupe_map m where h.member_ref = m.loser_id;

-- member_flags has a unique (member_ref, week_of, flag_type); flags are derived and
-- regenerated by the attendance engine, so just drop the losers' flags.
delete from public.member_flags f using _dupe_map m where f.member_ref = m.loser_id;

update public.member_links ml set member_id = m.keep_id
  from _dupe_map m where ml.member_id = m.loser_id;

-- Finally remove the duplicate rows.
delete from public.gym_members g using _dupe_map m where g.id = m.loser_id;

-- Show what was collapsed (for the run output).
select count(*) as rows_removed from _dupe_map;

commit;

notify pgrst, 'reload schema';
